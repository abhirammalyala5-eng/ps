import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.multioutput import MultiOutputRegressor
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_absolute_error, r2_score
import joblib
import os

# ------------------------------------------------------------
# 1. Load and clean dataset
# ------------------------------------------------------------
raw_dataset_path = "/content/drive/MyDrive/Nutrition_ML_Project/datasets/complete_dataset.csv"
fallback_path = "/content/drive/MyDrive/Nutrition_ML_Project/models/model1_dataset.csv"

if os.path.exists(raw_dataset_path):
    dataset_path = raw_dataset_path
else:
    dataset_path = fallback_path

print(f"Loading dataset for Regression: {dataset_path}")
df_reg = pd.read_csv(dataset_path).dropna(subset=['ingredient_name']).copy()

target_cols = ["energy_kcal", "carb_g", "protein_g", "fat_g", "fibre_g"]
for col in target_cols:
    df_reg[col] = pd.to_numeric(df_reg[col], errors='coerce').fillna(0)

# ------------------------------------------------------------
# 2. Extract Features and Split Data
# ------------------------------------------------------------
X_text = df_reg['ingredient_name'].astype(str).str.lower()
y = df_reg[target_cols]

X_train_text, X_test_text, y_train, y_test = train_test_split(
    X_text, y, test_size=0.2, random_state=42
)

# ------------------------------------------------------------
# 3. Text Representation via TF-IDF Vectorizer
# ------------------------------------------------------------
vectorizer_reg = TfidfVectorizer(ngram_range=(1, 3), max_features=10000)
X_train = vectorizer_reg.fit_transform(X_train_text)
X_test = vectorizer_reg.transform(X_test_text)

# ------------------------------------------------------------
# 4. Train the Multi-Output Ridge Regression Model
# ------------------------------------------------------------
base_regressor = Ridge(alpha=1.0)
model_reg = MultiOutputRegressor(base_regressor)
model_reg.fit(X_train, y_train)

# ------------------------------------------------------------
# 5. Evaluate Performance Metrics (MAE & R2)
# ------------------------------------------------------------
y_pred = model_reg.predict(X_test)

print("\n=== NUTRITION REGRESSION PERFORMANCE METRICS ===\n")
for i, col in enumerate(target_cols):
    mae = mean_absolute_error(y_test.iloc[:, i], y_pred[:, i])
    r2 = r2_score(y_test.iloc[:, i], y_pred[:, i])
    print(f"{col:15} -> Test MAE: {mae:10.4f} grams/kcal | R² Score: {r2:7.4f}")

