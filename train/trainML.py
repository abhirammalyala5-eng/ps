def predict_nutrition_regression(query):
    if isinstance(query, list):
        queries = [str(q).strip().lower() for q in query]
    elif isinstance(query, str):
        if "," in query:
            queries = [q.strip().lower() for q in query.split(",") if q.strip()]
        else:
            queries = [query.strip().lower()]
    else:
        queries = [str(query).strip().lower()]

    query_vectors = vectorizer_reg.transform(queries)
    predictions = model_reg.predict(query_vectors)
    # Physical Constraint Layer: Prevents impossible negative nutrition numbers
    predictions = np.clip(predictions, 0, None)

    return pd.DataFrame(predictions, columns=target_cols, index=queries)

