def predict_nutrition_smart(ingredient_name, min_similarity=0.15):
    query = str(ingredient_name).strip().lower()
    query_vector = vectorizer.transform([query])

    # Fetch top 15 candidates to filter through
    distances, indices = nn_model.kneighbors(query_vector, n_neighbors=15)

    results = []
    for distance, index in zip(distances[0], indices[0]):
        similarity = 1 - distance
        if similarity >= min_similarity:
            row = df.iloc[index]
            matched_name = row["ingredient_name"].lower()

            # Calculate a smart similarity boost
            adjusted_similarity = similarity

            # Boost exact matches or close base forms
            if matched_name == query:
                adjusted_similarity += 0.5
            elif matched_name.startswith(query + ",") or matched_name.startswith(query + " "):
                # e.g., "curd, plain" or "curd, whole milk"
                adjusted_similarity += 0.2

            # Penalize irrelevant modifiers if the query didn't ask for them
            penalties = ["lemon", "orange", "lime", "fruit", "cheese", "tart", "pie", "cake"]
            for penalty in penalties:
                if penalty in matched_name and penalty not in query:
                    adjusted_similarity -= 0.35

            result = {
                "matched_ingredient": row["ingredient_name"],
                "similarity_original": round(float(similarity), 4),
                "similarity_adjusted": round(float(adjusted_similarity), 4)
            }
            for col in nutrition_columns:
                result[col] = row[col]
            results.append(result)

    if not results:
        return pd.DataFrame()

    # Convert to DataFrame, sort by adjusted similarity, and return the top match
    res_df = pd.DataFrame(results)
    res_df = res_df.sort_values(by="similarity_adjusted", ascending=False).reset_index(drop=True)
    return res_df.head(1)

